CREATE TABLE software_installations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id INTEGER NOT NULL REFERENCES software_contracts(id) ON DELETE RESTRICT,
    asset_id INTEGER NOT NULL REFERENCES it_assets(id) ON DELETE RESTRICT,
    installation_no INTEGER NOT NULL,
    installed_on DATE NOT NULL,
    removed_on DATE,
    notes VARCHAR(5000),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ(3),
    CONSTRAINT software_installations_contract_id_installation_no_key UNIQUE (contract_id, installation_no),
    CONSTRAINT software_installations_dates_check CHECK (removed_on IS NULL OR removed_on >= installed_on)
);
CREATE INDEX software_installations_asset_id_idx ON software_installations(asset_id);
CREATE UNIQUE INDEX software_installations_active_asset_key ON software_installations(contract_id, asset_id) WHERE removed_on IS NULL AND deleted_at IS NULL;
CREATE TRIGGER software_installations_set_updated_at BEFORE UPDATE ON software_installations FOR EACH ROW EXECUTE FUNCTION public.set_record_updated_at();

CREATE TABLE software_installation_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id INTEGER NOT NULL REFERENCES software_installations(id) ON DELETE RESTRICT,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    usage_no INTEGER NOT NULL,
    started_on DATE NOT NULL,
    ended_on DATE,
    notes VARCHAR(5000),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ(3),
    CONSTRAINT software_installation_users_installation_id_usage_no_key UNIQUE (installation_id, usage_no),
    CONSTRAINT software_installation_users_dates_check CHECK (ended_on IS NULL OR ended_on >= started_on)
);
CREATE INDEX software_installation_users_employee_id_idx ON software_installation_users(employee_id);
CREATE UNIQUE INDEX software_installation_users_active_employee_key ON software_installation_users(installation_id, employee_id) WHERE ended_on IS NULL AND deleted_at IS NULL;
CREATE TRIGGER software_installation_users_set_updated_at BEFORE UPDATE ON software_installation_users FOR EACH ROW EXECUTE FUNCTION public.set_record_updated_at();

INSERT INTO permissions (name)
SELECT 'Operation: ' || code FROM unnest(ARRAY[
  'software.installations.create', 'software.installations.end',
  'software.usage.create', 'software.usage.end'
]) AS code
WHERE EXISTS (SELECT 1 FROM roles)
ON CONFLICT (name) DO NOTHING;

INSERT INTO permission_operations (operation, permission_id)
SELECT substring(p.name FROM 12), p.id FROM permissions p
WHERE p.name IN (
  'Operation: software.installations.create', 'Operation: software.installations.end',
  'Operation: software.usage.create', 'Operation: software.usage.end'
) AND p.deleted_at IS NULL
ON CONFLICT (operation) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id, scope_type)
SELECT r.id, po.permission_id, 'global'
FROM roles r CROSS JOIN permission_operations po
WHERE r.default_key = 'system_administrator' AND r.deleted_at IS NULL
  AND po.operation IN ('software.installations.create', 'software.installations.end', 'software.usage.create', 'software.usage.end')
  AND po.deleted_at IS NULL
ON CONFLICT (role_id, permission_id) DO NOTHING;
